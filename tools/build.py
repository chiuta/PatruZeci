"""Concatenates src/ into a single self-contained index.html (run from anywhere).

What the shared tooling (fff-kit `release` / `info`, inject-shared.mjs) adds to the page after the build is carried over
verbatim from the committed index.html: the kit block (<!--fff:kit:start-->…<!--fff:kit:end-->), the fff-info block, the
data-fff-hash attribute and the fff-mod-* modules. The Content-Security-Policy is then computed over EVERY executable inline
script of the final page, in document order, exactly as `fff-kit … fixcsp` does, so a rebuild reproduces the committed page and
the CI check "index.html is up to date with src/" stays meaningful after kit upgrades.

app.json belongs to the kit: after changing VERSION run
    python3 tools/build.py && node fff-kit/build.mjs release . --bump none --lax
(this script only warns when app.json disagrees with VERSION)."""
import pathlib, re, hashlib, base64, json
VERSION = '3.8.1'
UPDATED = '2026-11-17'
root = pathlib.Path(__file__).resolve().parent.parent
d = root / 'src'
css = (d / 'style.css').read_text(encoding='utf-8')
shell = (d / 'shell.html').read_text(encoding='utf-8').replace('__VERSION__', VERSION)
js = ''.join((d / f).read_text(encoding='utf-8') + '\n' for f in ['scenes.js', 'data.js', 'data_full.js', 'i18n.js', 'content_en.js'] + [f for f in ['content_fr.js','content_it.js','content_es.js','content_pt.js','content_de.js','content_hu.js'] if (d / f).exists()] + ['app.js'])
assert '</script' not in js
sw = ("if('serviceWorker' in navigator&&window.isSecureContext&&/^https?:$/.test(location.protocol))"
      "addEventListener('load',function(){var s=navigator.serviceWorker;s.register('./sw.js',{updateViaCache:'none'})"
      ".catch(function(){});s.ready.then(function(r){if(s.controller)return r.update()}).catch(function(){})})")
main = f'\n{js}\n'
def h(x):
    return "'sha256-" + base64.b64encode(hashlib.sha256(x.encode('utf8')).digest()).decode() + "'"
# Parts generated by the shared tooling are carried over verbatim from the committed index.html.
prev = (root / 'index.html').read_text(encoding='utf-8') if (root / 'index.html').exists() else ''
def carry(pattern):
    m = re.search(pattern, prev, re.S)
    return m.group(0) if m else ''
kit_html = carry(r'<!--fff:kit:start.*?<!--fff:kit:end-->\n?')
info_html = carry(r'<!--fff:info:start-->.*?<!--fff:info:end-->\n?')
if kit_html and not kit_html.endswith('\n'): kit_html += '\n'
hash_attr = (re.search(r'<html lang="ro"((?: data-fff-hash="[0-9a-f]*")?)', prev) or [None, ''])[1]
shared_html = ''.join(m.group(0) for m in re.finditer(r'<script id="fff-mod-[a-z0-9-]+">[\s\S]*?</script>\n?', prev))
body_html = f'''
{shell}
<script>{main}</script>
<script>{sw}</script>{shared_html}</body></html>'''
head_tail = f'''<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#0b131b">
<title>PATRUZECI — WD-40</title>
<meta name="description" content="Offline, illustrated and animated atlas of WD-40 uses. Unofficial. RO EN FR IT ES PT DE HU.">
<meta name="application-version" content="{VERSION}">
<meta name="last-updated" content="{UPDATED}">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" href="icon-192.png">
<link rel="apple-touch-icon" href="icon-192.png">
<style>{css}</style></head><body>'''
# CSP: hash of every executable inline script (classic or module; JSON data blocks excluded), in document order.
parts = [kit_html, info_html, head_tail, body_html]
scripts = []
for m in re.finditer(r'<script([^>]*)>(.*?)</script>', ''.join(parts), re.S):
    t = re.search(r'type\s*=\s*["\']?([^"\'\s>]+)', m.group(1))
    if 'src=' in m.group(1) or (t and t.group(1).lower() not in ('module', 'text/javascript')): continue
    scripts.append(h(m.group(2)))
csp = ("default-src 'none'; script-src " + ' '.join(scripts) +
       "; style-src 'unsafe-inline'; img-src 'self' data:; worker-src 'self'; connect-src 'none'; "
       "base-uri 'none'; form-action 'none'; manifest-src 'self'")
html = (f'<!doctype html>\n<html lang="ro"{hash_attr}><head><meta charset="utf-8">\n'
        f'{kit_html}{info_html}<meta http-equiv="Content-Security-Policy" content="{csp}">\n{head_tail}{body_html}')
out = root / 'index.html'
out.write_text(html, encoding='utf-8')
try:
    cur = json.loads((root / 'app.json').read_text(encoding='utf-8')).get('version')
except Exception:
    cur = None
if cur != VERSION:
    print(f'warning: app.json has version {cur!r}, build.py has {VERSION!r} — run: node fff-kit/build.mjs release . --bump none --lax')
print(out, len(html) // 1024, 'KB')
